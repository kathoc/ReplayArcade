# Writes src/core/FbneoRelative.inc: the FinalBurn Neo sets whose dial-like analog inputs (trackball,
# spinner, dial, knob, mouse, paddle, "Right / left") are speeds, with those inputs' names. FBNeo marks
# both these and plain sticks BIT_ANALOG_REL; a dial is one its driver reads through BurnTrackball*
# (the value is added up every frame), so that is the test: the input list of a driver in a source
# file that uses BurnTrackball. FbneoCore marks those layout axes relative (a mouse's motion drives them).
#
# usage: python3 -I make_fbneo_relative.py [--check] <FBNeo src/burn/drv> <output .inc>
import pathlib
import re
import sys

DIAL = re.compile(r"^(Trackball [XY]|Spinner( [XY])?|Dial|Analog Dial|Knob|Mouse [XY]|Paddle|Right / left)$")
INPUTS = re.compile(r"struct\s+BurnInputInfo\s+(\w+)InputList\s*\[\]\s*=\s*\{(.*?)\n\};", re.S)
ENTRY = re.compile(r'\{\s*"P(\d) ([^"]+)"\s*,\s*BIT_ANALOG_REL\b|A\(\s*"P(\d) ([^"]+)"\s*,\s*BIT_ANALOG_REL\b')
DRIVER = re.compile(r'struct\s+BurnDriver\w*\s+BurnDrv\w+\s*=\s*\{\s*"(\w+)"(.*?)\};', re.S)
CONSOLE_DIRS = {"channelf", "coleco", "gba", "megadrive", "msx", "nes", "pce", "sg1000", "sms", "snes", "spectrum"}


def main():
    args = sys.argv[1:]
    check = args[:1] == ["--check"]
    drv, out = map(pathlib.Path, args[1:3] if check else args[:2])
    rows = {}
    for p in sorted(drv.rglob("d_*.cpp")):
        if p.relative_to(drv).parts[0] in CONSOLE_DIRS:
            continue
        t = p.read_text(errors="ignore")
        if not re.search(r"\bBurnTrackball\w*\s*\(", t):
            continue
        lists = {}
        for m in INPUTS.finditer(t):
            names = sorted({n for n in (e.group(2) or e.group(4) for e in ENTRY.finditer(m.group(2))) if DIAL.match(n)})
            if names:
                lists[m.group(1)] = names
        for m in DRIVER.finditer(t):
            info = re.search(r"\b(\w+)InputInfo\s*,", m.group(2))
            if info and info.group(1) in lists:
                rows[m.group(1)] = lists[info.group(1)]
    text = ("// Generated by tools/make_fbneo_relative.py from FinalBurn Neo's drivers: do not edit.\n"
            "// {set, dial-like inputs that are speeds (FBNeo's names without \"P<n> \"), '|' separated}\n")
    text += "".join(f'{{"{s}", "{"|".join(n)}"}},\n' for s, n in sorted(rows.items()))
    if check:
        if not out.exists() or out.read_text() != text:
            sys.exit(f"{out} is out of date: run tools/make_fbneo_relative.py")
        print(f"{out}: up to date")
        return
    out.write_text(text)
    print(f"{len(rows)} sets")


if __name__ == "__main__":
    main()
