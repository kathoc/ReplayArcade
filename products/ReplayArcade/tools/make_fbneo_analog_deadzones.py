#!/usr/bin/env python3
"""Writes src/core/FbneoAnalogDeadzones.inc: for each set of a ROM folder with real analog position axes
(not FBNeo's fake stick for the d-pad, not dials), the value below which the game does not respond to
the axis, measured end to end with tools/analog_response (FinalBurn Neo's libretro dead zone plus the
driver's own: the Sega flight sticks and wheels respond from a third of the travel). FbneoCore gives it
to the frontend as the axis's "deadzone" hint, which starts a controller stick past it.

  tools/make_fbneo_analog_deadzones.py <build dir with dump_layout and analog_response> <ROM folder>

Axes the measurement cannot judge (fewer than MIN_STATES different states over the sweep: the game
does not read the axis at that point) are left out; FbneoCore keeps its libretro-only value for them.
"""
import json
import os
import re
import subprocess
import sys

MIN_STATES = 20
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "core", "FbneoAnalogDeadzones.inc")


def main():
    build, roms = sys.argv[1], sys.argv[2]
    rows = []
    for zip_name in sorted(os.listdir(roms)):
        if not zip_name.endswith(".zip"):
            continue
        path = os.path.join(roms, zip_name)
        out = subprocess.run([os.path.join(build, "dump_layout"), path], capture_output=True, text=True).stdout
        try:
            layout = json.loads(out.strip().splitlines()[-1])
        except (ValueError, IndexError):
            continue
        for axis in layout.get("axes", []):
            if axis.get("relative") or "Fake" in axis.get("label", "") or not axis["id"].startswith("p1."):
                continue
            res = subprocess.run([os.path.join(build, "analog_response"), path, axis["id"]], capture_output=True, text=True).stdout
            found = re.findall(r"first response at \|v\| = ([0-9.]+), (\d+) different states", res)
            if len(found) != 2 or min(int(n) for _, n in found) < MIN_STATES:
                continue
            dz = min(float(v) for v, _ in found)  # the side the game answers first: never past it
            rows.append((zip_name[:-4], axis["id"], dz))
            print(zip_name[:-4], axis["id"], dz, file=sys.stderr)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_fbneo_analog_deadzones.py (tools/analog_response over a ROM folder): do not edit.\n")
        f.write("// {set, axis id, the game's dead zone end to end (0..1; player 2's axes take player 1's)}\n")
        for s, a, dz in rows:
            f.write(f'{{"{s}", "{a}", {dz:.3f}f}},\n')


if __name__ == "__main__":
    main()
